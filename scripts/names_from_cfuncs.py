#!/usr/bin/env python3
"""Writes config/symbols/cfuncs.txt from the game's script command table.

The executable registers its script commands ("CFuncs") in a table of {const char* name, function} pairs in
.data (0x32E358, 943 entries; two functions are registered under two names each, the first one is kept).
Each function gets the name CFunc_<script name>, with the function pointer type of a CFunc.
"""

import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROM = ROOT / "disc" / "SLUS_216.72.rom"
BASE = 0x100000
TABLE = 0x32E358
COUNT = 943


def main():
    rom = ROM.read_bytes()

    def word(addr):
        return struct.unpack_from("<I", rom, addr - BASE)[0]

    def string(addr):
        end = rom.index(b"\0", addr - BASE)
        return rom[addr - BASE:end].decode()

    names = {}
    for i in range(COUNT):
        name, func = string(word(TABLE + 8 * i)), word(TABLE + 8 * i + 4)
        names.setdefault(func, name)
    lines = [f"CFunc_{name} = 0x{func:08X}; // type:func" for func, name in sorted(names.items())]
    lines.append(f"g_cfunc_table = 0x{TABLE:08X}; // size:0x{8 * COUNT:X}")
    out = ROOT / "config" / "symbols" / "cfuncs.txt"
    out.write_text("// Generated by scripts/names_from_cfuncs.py from the script command table.\n" + "\n".join(lines) + "\n")
    print(f"{len(names)} names -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
