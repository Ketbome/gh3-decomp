#!/usr/bin/env python3
"""Neversoft checksums ("QB keys"): names are hashed with CRC32 (reflected 0xEDB88320, initial 0xFFFFFFFF, no
final xor) over the lowercased text with '/' turned into '\\'.

Usage:
  scripts/qbkeys.py key <name...>                 print the checksum of each name
  scripts/qbkeys.py build [word sources...]       write config/qbkeys.txt: every checksum used as a constant in
                                                  the code whose name is found in the sources

Word sources are files or folders of text (e.g. decompiled QB scripts of the game); the executable's own strings and
the script command names (config/symbols/cfuncs.txt) are always used.
"""

import re
import sys
import zlib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "config" / "qbkeys.txt"


def qbkey(name):
    return ~zlib.crc32(name.lower().replace("/", "\\").encode()) & 0xFFFFFFFF


def words_from(path):
    files = [path] if path.is_file() else [p for p in path.rglob("*") if p.is_file()]
    words = set()
    for f in files:
        words.update(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", f.read_text(errors="ignore")))
    return words


def build(sources):
    words = set()
    for p in (ROOT / "asm" / "data").rglob("*.s"):
        words.update(re.findall(r'\.asciz "([^"]{1,80})"', p.read_text()))
    cfuncs = ROOT / "config" / "symbols" / "cfuncs.txt"
    if cfuncs.exists():
        words.update(m for m in re.findall(r"^CFunc_(\w+) =", cfuncs.read_text(), re.M))
    for src in sources:
        words.update(words_from(Path(src)))
    names = {}
    for w in sorted(words):
        names.setdefault(qbkey(w), w)
    used = Counter()
    for p in (ROOT / "asm").rglob("*.s"):
        for m in re.findall(r"\(0x([0-9A-F]+) >> 16\)", p.read_text()):
            used[int(m, 16)] += 1
    found = sorted((k, names[k]) for k in used if k in names)
    OUT.write_text("// checksum = name, for the checksums the code uses as constants. Generated by scripts/qbkeys.py.\n"
                   + "".join(f"0x{k:08X} = {n}\n" for k, n in found))
    print(f"{len(found)} of {len(used)} checksum constants named -> {OUT.relative_to(ROOT)}")


def main():
    if len(sys.argv) >= 3 and sys.argv[1] == "key":
        for name in sys.argv[2:]:
            print(f"0x{qbkey(name):08X}  {name}")
    elif len(sys.argv) >= 2 and sys.argv[1] == "build":
        build(sys.argv[2:])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
